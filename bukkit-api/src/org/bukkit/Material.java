    public boolean isBlock() { return block; }
    public boolean isItem() { return item; }
    public boolean isAir() { return this == AIR || this == CAVE_AIR || this == VOID_AIR; }
    public NamespacedKey getKey() { return NamespacedKey.minecraft(name().toLowerCase(Locale.ROOT)); }
    public static Material getMaterial(String name) { try { return valueOf(name); } catch (IllegalArgumentException e) { return null; } }
    public static Material matchMaterial(String name) {
        if (name == null) return null;
        String n = name.trim();
        if (n.toLowerCase(Locale.ROOT).startsWith("minecraft:")) n = n.substring(10);
        n = n.toUpperCase(Locale.ROOT).replaceAll("\\s+", "_").replaceAll("\\W", "");
        return getMaterial(n);
    }
