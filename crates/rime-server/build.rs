//! Generates block-state constants from `assets/<version>/blocks.tsv`.

use std::fmt::Write as _;
use std::path::Path;

const VERSION: &str = "26.1";

fn main() {
    let tsv_path = format!("assets/{VERSION}/blocks.tsv");
    println!("cargo:rerun-if-changed={tsv_path}");
    println!("cargo:rerun-if-changed=build.rs");
    let tsv = std::fs::read_to_string(&tsv_path).expect("blocks.tsv");
    let mut out = String::new();
    writeln!(out, "// @generated by build.rs from {tsv_path}").unwrap();
    writeln!(out, "pub const MC_VERSION: &str = \"{VERSION}\";").unwrap();
    let mut total = 0u32;
    for line in tsv.lines().filter(|l| !l.is_empty()) {
        let mut f = line.split('\t');
        let name = f.next().unwrap();
        let first: u32 = f.next().unwrap().parse().unwrap();
        let default: u32 = f.next().unwrap().parse().unwrap();
        let spec = f.next().unwrap_or("");
        let n: u32 = spec.split(';').filter(|s| !s.is_empty()).map(|p| p.split_once('=').unwrap().1.split(',').count() as u32).product();
        total = total.max(first + n.max(1));
        let ident = name.trim_start_matches("minecraft:").to_ascii_uppercase();
        writeln!(out, "pub const {ident}: BlockState = BlockState({default});").unwrap();
    }
    writeln!(out, "pub const STATE_COUNT: u32 = {total};").unwrap();
    let dest = Path::new(&std::env::var("OUT_DIR").unwrap()).join("blocks_gen.rs");
    std::fs::write(dest, out).unwrap();
}
